/** Union of every skill id — gives `tailoring.ts` compile-time safety. */
export type SkillId = (typeof allSkills)[number]['id'];

const hiddenSkills = new Set<string>(tailoring.hiddenSkills);
const pinnedOrder = new Map<string, number>(tailoring.pinnedSkills.map((id, i) => [id, i]));

/**
 * The list every component consumes: tailoring applied, pinned skills first,
 * original authoring order preserved for everything else.
 */
export const skills: Skill[] = allSkills
  .filter((s) => !hiddenSkills.has(s.id))
  .sort((a, b) => {
    const pa = pinnedOrder.get(a.id) ?? Number.POSITIVE_INFINITY;
    const pb = pinnedOrder.get(b.id) ?? Number.POSITIVE_INFINITY;
    if (pa !== pb) return pa - pb;
    return allSkills.indexOf(a) - allSkills.indexOf(b);
  });

export const skillById = new Map(skills.map((s) => [s.id, s]));

/** Only categories that still have at least one visible skill. */
export const activeCategories: SkillCategory[] = skillCategories.filter((c) =>
  skills.some((s) => s.category === c),
);

